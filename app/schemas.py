from typing import Literal

from pydantic import BaseModel, Field

DocType = Literal[
    "proposal",
    "meeting_minutes",
    "project_plan",
    "business_report",
    "technical_design",
    "sop",
    "product_spec",
]

ToolType = Literal["write_section", "make_table"]
TaskStatus = Literal["pending", "running", "done", "failed"]


class AgentRequest(BaseModel):
    """Incoming user request model."""

    request: str


class PlanTask(BaseModel):
    """Single planned task specification."""

    id: int
    title: str
    goal: str
    tool: ToolType


class PlannerOutput(BaseModel):
    """Output generated by the planning step."""

    doc_type: DocType
    title: str
    assumptions: list[str] = Field(default_factory=list)
    tasks: list[PlanTask] = Field(..., min_length=5, max_length=9)


class SectionContent(BaseModel):
    """Structured text content for written sections."""

    title: str
    paragraphs: list[str]
    bullet_points: list[str] = Field(default_factory=list)


class TableContent(BaseModel):
    """Structured table data and accompanying notes."""

    title: str
    description: str
    headers: list[str]
    rows: list[list[str]]


class TaskResult(BaseModel):
    """Execution output of a single task."""

    task_id: int
    title: str
    tool: ToolType
    status: TaskStatus
    content: SectionContent | TableContent | None = None
    error_message: str | None = None


class ReviewIssue(BaseModel):
    """Individual issue flagged during the review step."""

    section_id: int
    issue: str
    suggested_fix: str


class ReviewOutput(BaseModel):
    """Overall review findings and flag for required edits."""

    summary: str
    needs_fix: bool = False
    issues: list[ReviewIssue] = Field(default_factory=list)


class TaskSummary(BaseModel):
    """Status summary for a task in the final response."""

    id: int
    title: str
    status: TaskStatus


class AgentResponse(BaseModel):
    """Final API response returned after document generation."""

    run_id: str
    doc_type: str
    title: str
    summary: str
    assumptions: list[str]
    tasks: list[TaskSummary]
    review: ReviewOutput
    providers_used: list[str]
    download_url: str
    complete: bool


class HealthResponse(BaseModel):
    """Health check endpoint response."""

    status: str = "ok"
